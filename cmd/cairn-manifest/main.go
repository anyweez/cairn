// Command cairn-manifest writes a module's spec to a committed YAML file:
// every rule, every codec type stored in the ledger with its JSON shape, and
// every fsm table. A review then reads changes to the spec as a diff of that
// file rather than hunting for them in code.
//
//	cairn-manifest [-dir root] [-o spec.manifest.yaml] [-base old.yaml] [packages]
//
// Rules and tables are package-level variables, read from every file
// including tests. Codecs are codec.Register calls outside test files, since
// only production code writes to the ledger.
//
// The manifest does not depend on the host's platform: a file a build
// constraint excludes is read in a build that includes it, a file no build
// includes is an error naming the file and the constraint, and every registered
// type is resolved in every build the tool reads, so a JSON shape that differs
// between builds is an error naming the type and the files that declare it
// rather than the host's representation. A file a build includes but that does
// not type-check under it is an error carrying the loader's message naming the
// file, not a shape read from partial type information; a package that fails in
// a comparison build contributes no shape, so a platform the module is not used
// on does not refuse it.
//
// With -base, the manifest is also compared with an earlier one, and the
// command fails if a stored type changed in a way that breaks reading what is
// already in the ledger: removed, moved back a version, reshaped without a
// version bump, or bumped without an upcaster.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"
)

func main() {
	dir := flag.String("dir", ".", "the module to read")
	out := flag.String("o", "spec.manifest.yaml", "the manifest to write, relative to -dir; - for stdout")
	base := flag.String("base", "", "an earlier manifest (YAML, or the JSON of older versions), relative to the current directory, to check codec changes against")
	flag.Parse()
	patterns := flag.Args()
	if len(patterns) == 0 {
		patterns = []string{"./..."}
	}
	if err := run(*dir, *out, *base, patterns); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(dir, out, base string, patterns []string) error {
	m, err := Extract(dir, patterns...)
	if err != nil {
		return err
	}
	data, err := encode(m)
	if err != nil {
		return err
	}
	// Read the base before writing: -o defaults to spec.manifest.yaml in
	// -dir, so a local run that checks the committed manifest names the same
	// file for both. Read after the write and the check compares the manifest
	// with the copy it just produced.
	var raw []byte
	if base != "" {
		raw, err = os.ReadFile(base)
		if err != nil {
			return err
		}
	}
	if out == "-" {
		_, err = os.Stdout.Write(data)
	} else {
		err = os.WriteFile(filepath.Join(dir, out), data, 0o644)
	}
	if err != nil || base == "" {
		return err
	}

	// YAML is a superset of the JSON the manifest used to be written as, so
	// a base from before the switch still reads.
	var old Manifest
	if err := yaml.Unmarshal(raw, &old); err != nil {
		return fmt.Errorf("reading %s: %w", base, err)
	}
	if problems := Incompatible(&old, m); len(problems) > 0 {
		var b bytes.Buffer
		fmt.Fprintf(&b, "stored types changed incompatibly since %s:", base)
		for _, p := range problems {
			fmt.Fprintf(&b, "\n  %s", p)
		}
		return fmt.Errorf("%s", b.String())
	}
	return nil
}

const header = "# Generated by cmd/cairn-manifest. Do not edit: run\n#   go -C cmd/cairn-manifest run . -dir ../..\n"

func encode(m *Manifest) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(m); err != nil {
		return nil, err
	}
	err := enc.Close()
	return b.Bytes(), err
}

// Incompatible lists the codec changes from old to m that would break reading
// entries already stored under old.
func Incompatible(old, m *Manifest) []string {
	now := map[string]Codec{}
	for _, c := range m.Codecs {
		now[c.key()] = c
	}
	var problems []string
	for _, was := range old.Codecs {
		c, ok := now[was.key()]
		switch {
		case !ok:
			problems = append(problems, fmt.Sprintf("%s (%s) was removed; entries already stored with it can't be decoded", was.Name, was.Sum))
			continue
		case c.Version < was.Version:
			problems = append(problems, fmt.Sprintf("%s went back from version %d to %d", c.Name, was.Version, c.Version))
			continue
		case c.Version == was.Version && !sameFields(c.Fields, was.Fields):
			problems = append(problems, fmt.Sprintf("%s changed shape without a version bump (still version %d)", c.Name, c.Version))
		}
		// Entries may be stored at any version the base could read, so each
		// needs its path to the current version: the base's upcasters, and one
		// from every version since.
		needed := slices.Clone(was.Upcasts)
		for v := was.Version; v < c.Version; v++ {
			needed = append(needed, v)
		}
		slices.Sort(needed)
		for _, v := range slices.Compact(needed) {
			if !slices.Contains(c.Upcasts, v) {
				problems = append(problems, fmt.Sprintf("%s is version %d but has no upcaster from version %d", c.Name, c.Version, v))
			}
		}
	}
	return problems
}

// sameFields compares shapes by field, not by order: decoding matches JSON
// keys by name, so moving a field changes nothing that is stored. A struct
// nested in a field is rendered inline in the one string for that field, so
// this must hold at every depth: canonicalFields sorts the members of each
// nested struct before the two lists are compared.
func sameFields(a, b []string) bool {
	a, b = canonicalFields(a), canonicalFields(b)
	slices.Sort(a)
	slices.Sort(b)
	return slices.Equal(a, b)
}

// canonicalFields sorts the members of every struct in each rendered shape, so
// two manifests written by different field orders compare equal.
func canonicalFields(fields []string) []string {
	out := make([]string, len(fields))
	for i, f := range fields {
		out[i] = canonicalShape(f)
	}
	return out
}

// canonicalShape returns shape with the members of every struct it holds
// sorted, so reordering a nested struct's fields leaves it unchanged. The
// walk is recursive because a member's shape may hold structs of its own, and
// it counts brackets rather than searching for ", " because a generic type
// name or a function signature holds commas that do not separate members.
func canonicalShape(shape string) string {
	open := strings.IndexByte(shape, '{')
	if open < 0 {
		return shape
	}
	close, ok := matchingClose(shape, open)
	if !ok {
		// A shape the shaper does not normally produce: a JSON tag may hold "{",
		// which makes the rendering ambiguous. Compare it as it is rather than
		// risk folding two shapes that are not the same one.
		return shape
	}
	members := splitMembers(shape[open+1 : close])
	for i, m := range members {
		members[i] = canonicalShape(m)
	}
	slices.Sort(members)
	return shape[:open] + "{" + strings.Join(members, ", ") + "}" + canonicalShape(shape[close+1:])
}

// matchingClose returns the index of the bracket that closes the one at open.
func matchingClose(s string, open int) (int, bool) {
	depth := 0
	for i := open; i < len(s); i++ {
		switch s[i] {
		case '{', '[', '(':
			depth++
		case '}', ']', ')':
			depth--
			if depth == 0 {
				return i, true
			}
		}
	}
	return 0, false
}

// splitMembers splits a struct's rendered body at the commas that separate its
// fields, ignoring the commas nested in a member's own shape. Exactly the one
// space the shaper writes after a comma is dropped, so a JSON name that begins
// with a space keeps it.
func splitMembers(body string) []string {
	var members []string
	depth, start := 0, 0
	for i := 0; i < len(body); i++ {
		switch body[i] {
		case '{', '[', '(':
			depth++
		case '}', ']', ')':
			depth--
		case ',':
			if depth == 0 {
				members = append(members, body[start:i])
				start = i + 1
				if start < len(body) && body[start] == ' ' {
					start++
				}
			}
		}
	}
	return append(members, body[start:])
}
